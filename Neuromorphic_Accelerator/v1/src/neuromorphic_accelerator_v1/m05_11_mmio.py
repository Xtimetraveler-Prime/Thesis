"""M05.11b typed register protocol for OUR NEW AXI-Lite session slave.

This register map is defined by rtl/m05_11/m05_11_axil_session_controller.v;
it is NOT the AXI-Lite register map generated by Vitis HLS for the neural
kernel. The two AXI-Lite slaves must have separately allocated PS addresses.

No real memory mapping or Linux/PYNQ/PS DMA backend is implemented here.
A future backend must implement read32/write32 with trustworthy completion,
memory ordering and I/O errors. The host client refuses to ACK success until
a complete independently verified DMA frame was accepted.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Protocol

from .m05_execution_controller import RunPlan
from .m05_dma_frame import DMAFrameResult

CMD = 0x00
STATE = 0x04
SESSION_LO = 0x08
SESSION_HI = 0x0C
TRACE_ROWS_EXPECTED = 0x10
NEURON_BEATS = 0x14
SYNAPSE_BEATS = 0x18
EXTERNAL_BEATS = 0x1C
FINAL_STATUS = 0x20
TRACE_ROWS_OBSERVED = 0x24
NEURON_BEATS_OBSERVED = 0x28
SYNAPSE_BEATS_OBSERVED = 0x2C
EXTERNAL_BEATS_OBSERVED = 0x30
FLAGS = 0x34
VERSION = 0x38

MAGIC_VERSION = 0x0005110B
IDLE = 0
RUNNING = 1
FINALIZING = 2
COMPLETE = 3
FAULT = 4
START = 1
FINISH = 2
ACK = 4
MAX_U64 = (1 << 64) - 1


class SessionProtocolError(RuntimeError):
    """Register protocol or independently provided completion proof failed."""


class WordRegisterIO(Protocol):
    """Unimplemented physical PS MMIO abstraction, NOT a real driver."""
    def read32(self, offset: int) -> int: ...
    def write32(self, offset: int, value: int) -> None: ...


@dataclass(frozen=True)
class SessionSnapshot:
    state: int
    expected_rows: int
    observed_rows: int
    observed_inputs: tuple[int, int, int]
    flags: int


class M0511BridgeRegisters:
    def __init__(self, io: WordRegisterIO):
        self.io = io
        self._plan: RunPlan | None = None
        self._session: int | None = None
        self._started = False
        self._finalized = False

    def _read(self, offset: int) -> int:
        value = self.io.read32(offset)
        if type(value) is not int or not 0 <= value <= 0xFFFFFFFF:
            raise SessionProtocolError(f"bad MMIO read at {offset:#04x}")
        return value

    def _write(self, offset: int, value: int) -> None:
        if type(value) is not int or not 0 <= value <= 0xFFFFFFFF:
            raise SessionProtocolError("MMIO write outside unsigned32")
        self.io.write32(offset, value)

    def state(self) -> int:
        return self._read(STATE)

    def snapshot(self) -> SessionSnapshot:
        return SessionSnapshot(
            state=self.state(),
            expected_rows=self._read(TRACE_ROWS_EXPECTED),
            observed_rows=self._read(TRACE_ROWS_OBSERVED),
            observed_inputs=(
                self._read(NEURON_BEATS_OBSERVED),
                self._read(SYNAPSE_BEATS_OBSERVED),
                self._read(EXTERNAL_BEATS_OBSERVED),
            ),
            flags=self._read(FLAGS),
        )

    def configure(self, plan: RunPlan, session_id: int) -> None:
        if type(plan) is not RunPlan:
            raise TypeError("expected validated RunPlan")
        if type(session_id) is not int or not 0 <= session_id <= MAX_U64:
            raise ValueError("session ID must be unsigned64")
        if self._plan is not None:
            raise SessionProtocolError("prior session has not been acknowledged")
        if self._read(VERSION) != MAGIC_VERSION:
            raise SessionProtocolError("unexpected AXI-Lite bridge version")
        if self.state() != IDLE:
            raise SessionProtocolError("bridge not idle; hardware recovery required")
        cfg = (
            (SESSION_LO, session_id & 0xFFFFFFFF),
            (SESSION_HI, session_id >> 32),
            (TRACE_ROWS_EXPECTED, len(plan.neurons) * plan.ticks),
            (NEURON_BEATS, len(plan.neurons)),
            (SYNAPSE_BEATS, len(plan.synapses)),
            (EXTERNAL_BEATS, len(plan.external_events)),
        )
        for offset, value in cfg:
            self._write(offset, value)
        # Checking the independently read values catches gross MMIO decode,
        # address-map and unreliable writes before asserting START.
        for offset, value in cfg:
            if self._read(offset) != value:
                raise SessionProtocolError(
                    f"bridge config readback mismatch at {offset:#04x}"
                )
        self._plan = plan
        self._session = session_id

    def start(self) -> None:
        if self._plan is None or self._started or self._finalized:
            raise SessionProtocolError("no valid staged session or repeated start")
        if self.state() != IDLE:
            raise SessionProtocolError("hardware not idle at start")
        self._write(CMD, START)
        if self.state() != RUNNING:
            raise SessionProtocolError("start command not acknowledged")
        self._started = True

    def request_finish(self, *, hls_done_latched: bool,
                       actual_hls_status: int) -> None:
        if (self._plan is None or not self._started or self._finalized
                or self.state() != RUNNING):
            raise SessionProtocolError("no running session to finalize")
        if hls_done_latched is not True:
            raise SessionProtocolError("real HLS ap_done has not been latched")
        if (type(actual_hls_status) is not int
                or not 0 <= actual_hls_status <= 6):
            raise SessionProtocolError("invalid independently read ap_return")
        self._write(FINAL_STATUS, actual_hls_status)
        if self._read(FINAL_STATUS) != actual_hls_status:
            raise SessionProtocolError("finish status register readback mismatch")
        self._write(CMD, FINISH)
        if self.state() not in (FINALIZING, COMPLETE, FAULT):
            raise SessionProtocolError("finalize command not acknowledged")
        self._finalized = True

    def acknowledge_success(self, frame: DMAFrameResult) -> None:
        """ACK only after a separate S2MM/TLAST/byte-count/frame verifier.

        Caller must also establish true transport quiescence; DMAFrameResult
        is only returned by accept_dma_frame after that was attested.
        """
        if (self._plan is None or self._session is None
                or not self._started or not self._finalized):
            raise SessionProtocolError("no finalized session")
        if type(frame) is not DMAFrameResult:
            raise TypeError("expected verified DMAFrameResult")
        if (frame.session_id != self._session or frame.hls_status != 0
                or not frame.result.accepted or
                frame.received_trace_beats != len(self._plan.neurons) * self._plan.ticks):
            raise SessionProtocolError("DMA frame does not certify this successful session")
        snap = self.snapshot()
        if snap.state != COMPLETE or snap.observed_rows != snap.expected_rows:
            raise SessionProtocolError("hardware session not fully complete")
        expected_inputs = (len(self._plan.neurons), len(self._plan.synapses),
                           len(self._plan.external_events))
        if snap.observed_inputs != expected_inputs:
            raise SessionProtocolError("bridge ingress accepted beat counts mismatch")
        if snap.flags & 0x02:
            raise SessionProtocolError("bridge fault flag asserted")
        self._write(CMD, ACK)
        if self.state() != IDLE:
            raise SessionProtocolError("ACK did not restore idle")
        self._plan = None
        self._session = None
        self._started = False
        self._finalized = False

    def fault_requires_external_reset(self) -> bool:
        return self.state() == FAULT

    def notify_externally_verified_reset(self) -> None:
        """Software ownership reset ONLY after actual full DMA/PL reset fence.

        This method itself does not reset any hardware. An integration driver
        must perform and independently attest completed full reset/flush.
        """
        if self.state() != IDLE:
            raise SessionProtocolError("bridge reset was not verified by MMIO")
        self._plan = None
        self._session = None
        self._started = False
        self._finalized = False
