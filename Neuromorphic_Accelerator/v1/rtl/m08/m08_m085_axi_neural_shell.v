// M08.5 SOURCE-ONLY recurrent LIF + seven distinct AXI4 page slots.
// The sixth neural page is slot 5; SEVENTH slot 6 is M6EG edge config,
// whose semantic bank page ID remains 0xFFFFFFFF. Both use ONE resident
// 64-word bank. This is a connected real first-party COMPUTE path, NOT
// a Vivado implementation, PL/PS route, DMA, or physical K26 DDR proof.
//
// External future owner must sequence: LOAD edge(transport slot6, tick0),
// dispatch semantic 0xFFFFFFFF, verified SAVE edge; then for each tick
// 0..3 and each neural slot 0..5: LOAD, dispatch semantic slot, SAVE,
// preserving each 256B page. No golden neural trace enters hardware.
// Window defaults to zero, hence absolutely no transactions admitted.
// Physical PS HP0 remains UNCONNECTED. Callers must authenticate
// memory ownership through a separate future kernel/standalone gate.
